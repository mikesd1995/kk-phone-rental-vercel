const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const current=fs.readFileSync(path.join(root,'admin','admin.css'),'utf8');
const v3=fs.readFileSync(path.join(root,'admin','admin-ux-v3.css'),'utf8');
const v2=fs.readFileSync(path.join(root,'admin','admin-ux-v2.css'),'utf8');
const v1=fs.readFileSync(path.join(root,'admin','admin-ux-v1.css'),'utf8');
const base=fs.readFileSync(path.join(root,'admin','admin-base.css'),'utf8');
const html=fs.readFileSync(path.join(root,'admin','index.html'),'utf8');
const combined=base+'\n'+v1+'\n'+v2+'\n'+v3+'\n'+current;
test('Admin refresh preserves the full stylesheet rollback chain',()=>{assert.match(current,/admin-ux-v3\.css/);assert.match(v3,/admin-ux-v2\.css/);assert.match(v2,/admin-ux-v1\.css/);assert.match(v1,/admin-base\.css/);assert.ok(v3.length>5000);assert.ok(v2.length>5000);assert.ok(v1.length>5000);assert.ok(base.length>5000);});
test('Admin refresh stack retains hierarchy responsive and accessibility rules',()=>{assert.match(v1,/--ux-sidebar:#0f172a/);assert.match(combined,/\.sidebar\{/);assert.match(combined,/\.pro-hero\{/);assert.match(combined,/@media\(max-width:680px\)/);assert.match(combined,/:focus-visible/);});
test('Admin DOM contract remains intact',()=>{assert.match(html,/id="appPanel"/);assert.match(html,/id="statsGrid"/);assert.match(html,/id="bookingForm"/);assert.match(html,/id="eventForm"/);assert.match(html,/\/admin\/admin\.css\?v=/);});
